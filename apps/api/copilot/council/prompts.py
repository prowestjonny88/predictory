def council_language_prefix(language: str) -> str:
    if language == "ms":
        return (
            "Respond in clear operational Bahasa Melayu. Keep outlet/place names and SKU product "
            "names exactly as provided."
        )
    if language == "zh-CN":
        return (
            "Respond in clear operational Simplified Chinese. Keep outlet/place names and SKU product "
            "names exactly as provided."
        )
    return "Respond in clear operational English. Keep outlet/place names and SKU product names exactly as provided."


